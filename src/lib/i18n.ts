const STORAGE_KEY = 'ss-gacha-pool-lang'

/** 从缓存或浏览器推断语言 */
export function detectLanguage(): Lang {
  if (typeof localStorage !== 'undefined') {
    const saved = localStorage.getItem(STORAGE_KEY)
    if (saved && LANGUAGES.includes(saved as Lang)) return saved as Lang
  }
  if (typeof navigator !== 'undefined') {
    const browser = navigator.language.toLowerCase()
    if (browser.startsWith('ja')) return 'JP'
    if (browser.startsWith('ko')) return 'KR'
    if (browser.startsWith('zh-tw') || browser.startsWith('zh-hk')) return 'TW'
    if (browser.startsWith('zh')) return 'CN'
  }
  return 'CN'
}

/** 持久化所选语言 */
export function saveLanguage(lang: Lang): void {
  if (typeof localStorage !== 'undefined') localStorage.setItem(STORAGE_KEY, lang)
}

/** 翻译界面文案 支持占位符替换 */
export function t(lang: Lang, key: string, params: Record<string, string | number> = {}): string {
  let text = COPY[lang]?.[key] ?? COPY.CN[key] ?? key
  for (const [name, value] of Object.entries(params)) {
    text = text.replaceAll(`{${name}}`, String(value))
  }
  return text
}

/** 从名称表取当前语言的值 */
export function localized(value: Record<string, string> | undefined, lang: Lang): string {
  if (!value) return ''
  return value[lang] ?? value.CN ?? Object.values(value)[0] ?? ''
}
